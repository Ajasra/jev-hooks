def capability_manifest() -> dict[str, Any]:
    return {
        feature.id: {
            "version": feature.version,
            "triggers": sorted(trigger.value for trigger in feature.triggers),
            "required_capabilities": sorted(feature.required_capabilities),
            "failure_policy": feature.failure_policy,
        }
        for feature in FEATURES
    }


OPENCODE_PLUGIN_HEADER = "// @jev-owned - generated by `jev install opencode`; do not edit by hand."

OPENCODE_PRE_FILTER = (
    "read", "glob", "grep", "list", "lsp", "skill", "todowrite", "question", "webfetch", "websearch",
)

OPENCODE_HOOK_BY_KIND = {
    EventKind.TURN_BEFORE: "chat.message",
    EventKind.TOOL_BEFORE: "tool.execute.before",
    EventKind.TOOL_AFTER: "tool.execute.after",
    EventKind.CONTEXT_CHECKPOINT: "experimental.session.compacting",
}

OPENCODE_DRAIN_HOOK = "experimental.chat.system.transform"

OPENCODE_DECLARED_LIFECYCLE = (
    EventKind.TURN_BEFORE,
    EventKind.TOOL_BEFORE,
    EventKind.TOOL_AFTER,
    EventKind.CONTEXT_CHECKPOINT,
)


def opencode_subscriptions() -> dict[str, str]:
    claimed = {kind for feature in FEATURES for kind in feature.triggers}
    kinds = claimed | set(OPENCODE_DECLARED_LIFECYCLE)
    return {
        hook: kind.value
        for kind, hook in OPENCODE_HOOK_BY_KIND.items()
        if kind in kinds
    }


def opencode_timeouts() -> dict[str, int]:
    subscriptions = opencode_subscriptions()
    timeouts: dict[str, int] = {}
    for kind, hook in OPENCODE_HOOK_BY_KIND.items():
        if hook not in subscriptions:
            continue
        secure = any(kind in feature.triggers and feature.failure_policy == "secure" for feature in FEATURES)
        timeouts[hook] = 1000 if secure else 750
    return timeouts


def opencode_config(python: str = "python", skills_path: str = "") -> dict[str, Any]:
    config: dict[str, Any] = {
        "mcp": {
            "jev": {
                "type": "local",
                "command": [python, "-m", "jev", "mcp", "--cwd", ".", "--harness", "opencode"],
                "enabled": True,
            }
        }
    }
    if skills_path:
        config["skills"] = {"paths": [skills_path]}
    return config


def opencode_plugin(python: str = "python", harness_version: str = "") -> str:
    subscriptions = opencode_subscriptions()
    hooks = "".join(f'  {json.dumps(hook)}: {json.dumps(kind)},\n' for hook, kind in subscriptions.items())
    timeouts = opencode_timeouts()
    timeout_lines = "".join(f"  {json.dumps(hook)}: {value},\n" for hook, value in timeouts.items())
    pre_filter = ", ".join(json.dumps(name) for name in OPENCODE_PRE_FILTER)
    source = (
        OPENCODE_JEV_TS.replace("@@HEADER@@", OPENCODE_PLUGIN_HEADER)
        .replace("@@PYTHON@@", json.dumps(python))
        .replace("@@HARNESS_VERSION@@", json.dumps(harness_version))
        .replace("@@PRE_FILTER@@", pre_filter)
        .replace("@@HOOKS@@", hooks.rstrip("\n"))
        .replace("@@TIMEOUTS@@", timeout_lines.rstrip("\n"))
    )
    return source
